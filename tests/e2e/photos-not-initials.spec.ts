import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import {
  expect,
  test,
  type APIRequestContext,
  type Browser,
  type Page,
} from '@playwright/test';
import { tipFromProfile } from '../shared/tip-flow';
import { signUpRecipient } from './helpers';
import { accountOf, seedBusiness } from './business-fixtures';
import { sql } from './ops-helpers';
import { WEB_ORIGIN } from './stack';

// Photos, not initials (owner, 14 Nov 2026): the receipt, the share card and a printed sign show
// the person's photo or the business's logo when there is one, and initials only when not. Every
// picture here is generated by the test (a flat colour), never a real photo.

type Raw = { data: Buffer; info: { width: number; height: number } };
type Sharp = {
  jpeg(): { toBuffer(): Promise<Buffer> };
  ensureAlpha(): {
    raw(): { toBuffer(o: { resolveWithObject: true }): Promise<Raw> };
  };
};
// sharp is the API's dependency (resolved from there), as in business-codes.spec.ts.
const sharp = createRequire(resolve('apps/api/package.json'))('sharp') as (
  input:
    | Buffer
    | {
        create: {
          width: number;
          height: number;
          channels: 3;
          background: { r: number; g: number; b: number };
        };
      },
) => Sharp;
type Decode = (
  data: Uint8ClampedArray,
  w: number,
  h: number,
) => { data: string } | null;
const jsQR = createRequire(resolve('apps/web/package.json'))('jsqr') as Decode;

/** A generated picture of one flat colour. */
const flat = (r: number, g: number, b: number, width = 600, height = 600) =>
  sharp({
    create: { width, height, channels: 3, background: { r, g, b } },
  })
    .jpeg()
    .toBuffer();
const ORANGE = { r: 230, g: 120, b: 20 };

const pixels = (png: Buffer) =>
  sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const pixelAt = ({ data, info }: Raw, x: number, y: number) => {
  const at = (Math.round(y) * info.width + Math.round(x)) * 4;
  return { r: data[at]!, g: data[at + 1]!, b: data[at + 2]! };
};
const near = (
  a: { r: number; g: number; b: number },
  b: { r: number; g: number; b: number },
) =>
  Math.abs(a.r - b.r) < 24 &&
  Math.abs(a.g - b.g) < 24 &&
  Math.abs(a.b - b.b) < 24;

const setName = (handle: string, name: string) =>
  sql('UPDATE profiles SET display_name = $2 WHERE handle_lower = $1', [
    handle,
    name,
  ]);

async function uploadPhoto(page: Page) {
  await page.goto('/dashboard/settings');
  await page.getByLabel('Choose a photo').setInputFiles({
    name: 'me.jpg',
    mimeType: 'image/jpeg',
    buffer: await flat(ORANGE.r, ORANGE.g, ORANGE.b),
  });
  await expect(page.getByText('Photo saved.')).toBeVisible();
}

/** A visitor tips the page and lands on the paid receipt, left open for the test. */
async function paidReceipt(browser: Browser, handle: string, name: string) {
  const page = await (await browser.newContext()).newPage();
  await expect(async () => {
    await page.goto(`/@${handle}`);
    await expect(page.getByRole('radio', { name: '2,000 NGN' })).toBeVisible({
      timeout: 1000,
    });
  }).toPass({ timeout: 10_000 });
  await tipFromProfile(page);
  await expect(
    page.getByRole('heading', { name: `${name} got your thanks.` }),
  ).toBeVisible({ timeout: 20_000 });
  return page.locator('.tip-thanks');
}

/** The person's share card: 200 and a PNG, whatever the photo does. */
async function card(request: APIRequestContext, handle: string) {
  const response = await request.get(`/people/${handle}/share-card`);
  expect(response.status()).toBe(200);
  expect(response.headers()['content-type']).toBe('image/png');
  return response.body();
}
// The face's centre on the 1200 × 630 card (share-card.tsx: band 168, face 152 at left 72).
const FACE_CENTRE = { x: 72 + 76, y: 168 };

test('the receipt and the share card show the recipient’s photo once they have one', async ({
  page,
  browser,
  request,
}, testInfo) => {
  const { handle } = await signUpRecipient(page, testInfo);
  await setName(handle, 'Kemi Adeyemi');
  // No photo yet: the share card's face is the initials on the cover colour.
  const initialsCard = await pixels(await card(request, handle));
  expect(
    near(pixelAt(initialsCard, FACE_CENTRE.x, FACE_CENTRE.y + 40), ORANGE),
  ).toBe(false);

  await uploadPhoto(page);
  // Found in the sweep: the dashboard's page card showed the monogram even with a photo.
  await page.goto('/dashboard');
  const own = page.locator('.page-card__monogram img');
  await expect
    .poll(() => own.evaluate((img: HTMLImageElement) => img.naturalWidth))
    .toBeGreaterThan(0);

  const receipt = await paidReceipt(browser, handle, 'Kemi Adeyemi');
  const photo = receipt.locator('.tip-thanks__mark img');
  await expect(photo).toHaveAttribute(
    'src',
    /\/v1\/avatars\/[0-9a-f-]+\/\d+\.webp$/,
  );
  await expect
    .poll(() => photo.evaluate((img: HTMLImageElement) => img.naturalWidth))
    .toBeGreaterThan(0);
  await expect(receipt.locator('.tip-thanks__mark')).not.toContainText('K');

  // The share card draws the same photo in the face (the page's cache updates within seconds).
  await expect(async () => {
    const drawn = await pixels(await card(request, handle));
    expect(
      near(pixelAt(drawn, FACE_CENTRE.x, FACE_CENTRE.y + 40), ORANGE),
    ).toBe(true);
  }).toPass({ timeout: 15_000 });
});

test('without a photo the receipt shows the initial and the share card still answers', async ({
  page,
  browser,
  request,
}, testInfo) => {
  const { handle } = await signUpRecipient(page, testInfo);
  await setName(handle, 'Kemi Adeyemi');
  await card(request, handle);
  const receipt = await paidReceipt(browser, handle, 'Kemi Adeyemi');
  await expect(receipt.locator('.tip-thanks__mark img')).toHaveCount(0);
  await expect(receipt.locator('.tip-thanks__initial')).toHaveText('K');
});

test('a business with a logo downloads a sign whose tile is the logo, and the code is unchanged', async ({
  page,
}, testInfo) => {
  const who = await signUpRecipient(page, testInfo);
  const { userId } = await accountOf(who.email);
  const { slug } = await seedBusiness({
    owner: userId,
    name: 'Kiosk Ade',
    locations: [{ slug: 'vi', name: 'Victoria Island' }],
  });
  const url = `${WEB_ORIGIN}/b/${slug}/vi?src=qr`;
  const download = async () => {
    await page.goto('/dashboard/business');
    const codes = page.getByRole('region', { name: 'Codes' });
    const file = page.waitForEvent('download');
    await codes
      .getByRole('button', { name: 'Download Victoria Island sign' })
      .click();
    const path = await (await file).path();
    return pixels(await readFile(path));
  };
  // The tile's centre on a 1240 px wide sign (business-sign.ts: tile 13% wide, 8% down).
  const tileCentre = (raw: Raw) => {
    const tile = Math.round(raw.info.width * 0.13);
    return pixelAt(
      raw,
      raw.info.width / 2 - tile * 0.3,
      Math.round(raw.info.height * 0.08) + tile * 0.2,
    );
  };

  const before = await download();
  expect(near(tileCentre(before), ORANGE)).toBe(false);

  await page.goto('/dashboard/business');
  const details = page.getByRole('region', { name: 'Details' });
  await details.getByLabel('Choose a logo').setInputFiles({
    name: 'logo.jpg',
    mimeType: 'image/jpeg',
    buffer: await flat(ORANGE.r, ORANGE.g, ORANGE.b, 600, 400),
  });
  await expect(
    details.getByRole('status').getByText('Logo saved.'),
  ).toBeVisible();

  const after = await download();
  expect(after.info).toEqual(before.info);
  expect(near(tileCentre(after), ORANGE)).toBe(true);
  // The same code either way.
  for (const raw of [before, after])
    expect(
      jsQR(new Uint8ClampedArray(raw.data), raw.info.width, raw.info.height)
        ?.data,
    ).toBe(url);
});
